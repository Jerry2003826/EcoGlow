CREATE TABLE `users` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `email` VARCHAR(255) NOT NULL,
    `password` VARCHAR(255) NOT NULL,
    `password_reset_token` VARCHAR(255) NULL DEFAULT NULL,
    `password_reset_expires` DATETIME NULL DEFAULT NULL,
    `created` DATETIME NOT NULL,
    `modified` DATETIME NOT NULL,
    `first_name` VARCHAR(100) NULL,
    `last_name` VARCHAR(100) NULL,
    `phone` VARCHAR(32) NULL,
    `role` VARCHAR(30) NOT NULL DEFAULT 'customer',
    `status` VARCHAR(30) NOT NULL DEFAULT 'active',
    `email_verified_at` DATETIME(6) NULL,
    `last_login_at` DATETIME(6) NULL,
    `failed_login_count` INT NOT NULL DEFAULT 0,
    `locked_until` DATETIME(6) NULL,
    `mfa_enabled` TINYINT(1) NOT NULL DEFAULT 0,
    `mfa_secret_reference` VARCHAR(255) NULL,
    `mfa_enrolled_at` DATETIME(6) NULL,
    `last_password_change_at` DATETIME(6) NULL,
    `metadata` JSON NOT NULL DEFAULT (JSON_OBJECT()),
    `preferred_locale` VARCHAR(20) NOT NULL DEFAULT 'en-AU',
    `timezone` VARCHAR(80) NOT NULL DEFAULT 'Australia/Melbourne',
    `deleted` DATETIME(6) NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_users_email` (`email`),
    KEY `idx_users_password_reset_token` (`password_reset_token`),
    KEY `idx_users_role_status` (`role`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
